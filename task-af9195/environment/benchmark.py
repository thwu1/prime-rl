"""Moving Peaks Benchmark for Dynamic Optimization.

The landscape is defined as:
    f(x) = max_{i=1}^{m} h_i / (1 + w_i * ||x - c_i||^2)

where h_i, c_i, w_i are the height, center, and sharpness of peak i.
Peaks shift, change height, and adjust sharpness at regular intervals.

Reference: D. Yazdani et al., "Competition on Dynamic Optimization Problems
Generated by Generalized Moving Peaks Benchmark (GMPB)," arXiv:2106.06174.
"""


import numpy as np


class MovingPeaksBenchmark:
    """Dynamic benchmark with shifting peaks.

    Parameters
    ----------
    num_peaks : int
        Number of peaks in the landscape.
    dimension : int
        Number of decision variables.
    change_frequency : int
        Number of fitness evaluations between environment changes.
    shift_severity : float
        Magnitude of peak position shift at each change.
    num_environments : int
        Total number of environments (including the initial one).
    seed : int
        Random seed for reproducibility.
    height_range : tuple
        (min, max) for peak heights.
    width_range : tuple
        (min, max) for peak sharpness values.
    height_severity : float
        Standard deviation of height change per peak per change event.
    width_severity : float
        Standard deviation of width change per peak per change event.
    bounds : tuple
        (lower, upper) bounds for each decision variable.
    correlation : float
        Correlation factor for shift direction (0=random, 1=same as previous).
    """

    def __init__(self, num_peaks, dimension, change_frequency,
                 shift_severity, num_environments, seed=42,
                 height_range=(30.0, 70.0), width_range=(0.001, 0.01),
                 height_severity=7.0, width_severity=0.001,
                 bounds=(0.0, 100.0), correlation=0.5):
        self.num_peaks = num_peaks
        self.dimension = dimension
        self.change_frequency = change_frequency
        self.shift_severity = shift_severity
        self.num_environments = num_environments
        self.height_range = height_range
        self.width_range = width_range
        self.height_severity = height_severity
        self.width_severity = width_severity
        self.bounds = bounds
        self.correlation = correlation

        self.rng = np.random.RandomState(seed)
        lb, ub = bounds

        self.heights = self.rng.uniform(height_range[0], height_range[1], num_peaks)
        self.centers = self.rng.uniform(lb, ub, (num_peaks, dimension))
        self.widths = self.rng.uniform(width_range[0], width_range[1], num_peaks)
        self.velocities = np.zeros((num_peaks, dimension))

    @property
    def total_evaluations(self):
        return self.change_frequency * self.num_environments

    def evaluate(self, x):
        """Evaluate the landscape at point x.

        Parameters
        ----------
        x : array-like of shape (dimension,)

        Returns
        -------
        float
            Landscape value (higher is better).
        """
        x = np.asarray(x, dtype=float)
        diffs = x - self.centers                       # (m, d)
        r_sq = np.sum(diffs ** 2, axis=1)              # (m,)
        values = self.heights / (1.0 + self.widths * r_sq)  # (m,)
        return float(np.max(values))

    def get_optimum(self):
        """Return (position, value) of the current global optimum.

        The optimum is at the center of the tallest peak.
        """
        best_idx = int(np.argmax(self.heights))
        return self.centers[best_idx].copy(), float(self.heights[best_idx])

    def trigger_change(self):
        """Apply one environment change: shift peaks and modify heights/widths."""
        lb, ub = self.bounds
        lam = self.correlation

        for i in range(self.num_peaks):
            # Correlated random shift direction
            r = self.rng.randn(self.dimension)
            combined = lam * r + (1.0 - lam) * self.velocities[i]
            norm = np.linalg.norm(combined)
            if norm > 1e-10:
                self.velocities[i] = self.shift_severity * combined / norm
            else:
                r_norm = np.linalg.norm(r)
                self.velocities[i] = self.shift_severity * r / (r_norm + 1e-10)

            # Update position with boundary reflection
            new_center = self.centers[i] + self.velocities[i]
            for d in range(self.dimension):
                while new_center[d] < lb or new_center[d] > ub:
                    if new_center[d] < lb:
                        new_center[d] = 2.0 * lb - new_center[d]
                    if new_center[d] > ub:
                        new_center[d] = 2.0 * ub - new_center[d]
            self.centers[i] = new_center

            # Update height
            new_h = self.heights[i] + self.height_severity * self.rng.randn()
            self.heights[i] = np.clip(new_h, self.height_range[0], self.height_range[1])

            # Update width (sharpness)
            new_w = self.widths[i] + self.width_severity * self.rng.randn()
            self.widths[i] = np.clip(new_w, self.width_range[0], self.width_range[1])
