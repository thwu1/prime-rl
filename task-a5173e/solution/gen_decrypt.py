print("  - Inverse S-box: 256 entries computed from forward S-box")
print("  - GF(2^8) multiplication: gf_mul9, gf_mul11, gf_mul13, gf_mul14")
print("  - InvShiftRows: circular right-shift rows by 0/1/2/3")
print("  - InvMixColumns: inverse MDS matrix with {0e,0b,0d,09}")
print("  - FSM: IDLE -> KEY_EXPAND (10 cyc) -> DECRYPT (10 cyc) -> DONE")
