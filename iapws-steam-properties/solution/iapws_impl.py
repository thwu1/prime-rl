def properties_region3(T, rho):
    delta = rho/rhoc; tau = Tc/T
    n1 = _R3[0][2]
    f = n1*math.log(delta); fd = n1/delta; fdd = -n1/(delta*delta)
    ft = ftt = fdt = 0.0
    for k in range(1, 40):
        I,J,n = _R3[k]
        dI = delta**I if I != 0 else 1.0
        tJ = tau**J if J != 0 else 1.0
        f += n*dI*tJ
        if I >= 1: fd += n*I*delta**(I-1)*tJ
        if I >= 2: fdd += n*I*(I-1)*delta**(I-2)*tJ
        if J >= 1: ft += n*dI*J*tau**(J-1)
