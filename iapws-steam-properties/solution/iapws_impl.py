# ================================================================
_nsat = [0.11670521452767e4, -0.72421316703206e6, -0.17073846940092e2,
         0.12020824702470e5, -0.32325550322333e7, 0.14915108613530e2,
         -0.48232657361591e4, 0.40511340542057e6, -0.23855557567849e0,
         0.65017534844798e3]

def saturation_pressure(T):
    n = _nsat
    th = T + n[8] / (T - n[9])
    A = th*th + n[0]*th + n[1]
    B = n[2]*th*th + n[3]*th + n[4]
    C = n[5]*th*th + n[6]*th + n[7]
    return (2.0*C / (-B + math.sqrt(B*B - 4.0*A*C)))**4

def saturation_temperature(p):
    n = _nsat
    b = p**0.25
    E = b*b + n[2]*b + n[5]
    F = n[0]*b*b + n[3]*b + n[6]
    G = n[1]*b*b + n[4]*b + n[7]
    D = 2.0*G / (-F - math.sqrt(F*F - 4.0*E*G))
    return (n[9]+D - math.sqrt((n[9]+D)**2 - 4.0*(n[8]+n[9]*D)))/2.0

# ================================================================
# B23 boundary
# ================================================================
def _b23_p(T):
    return 348.05185628969 - 1.1671859879975*T + 0.10192970039326e-2*T*T

def _b23_T(p):
    return 572.54459862746 + math.sqrt((p - 13.91883977870) / 0.10192970039326e-2)

# ================================================================
# Region detection
# ================================================================
def region(T, p):
    if 1073.15 < T <= 2273.15 and 0 < p <= 50:
        return 5
    if T > 1073.15 or T < 273.15 or p <= 0 or p > 100:
        raise ValueError(f"T={T}, p={p} out of IF-97 range")
    if 273.15 <= T <= 623.15:
        ps = saturation_pressure(T)
        return 1 if p > ps else 2
    else:
        return 3 if p > _b23_p(T) else 2

