def viscosity(rho, T):
    Tr = T/Tc; Dr = rho/rhoc
    denom = sum(H/Tr**i for i,H in enumerate(_mu_H0))
    mu0 = 100.0*math.sqrt(Tr)/denom
    exp_arg = sum((1.0/Tr-1.0)**i * h * (Dr-1.0)**j for i,j,h in _mu_Hr)
    mu1 = math.exp(Dr * exp_arg)
    return mu0 * mu1 * 1e-6

