def properties_region1(T, p):
    tau = 1386.0/T; pi = p/16.53
    pr = pi - 7.1; tr = tau - 1.222
    g = gp = gpp = gt = gtt = gpt = 0.0
    for I,J,n in _R1:
        pI = pr**I if I != 0 else 1.0
        tJ = tr**J if J != 0 else 1.0
        g += n * pI * tJ
        if I >= 1:
            gp += n * I * pr**(I-1) * tJ
        if I >= 2:
            gpp += n * I*(I-1) * pr**(I-2) * tJ
        if J != 0:
            gt += n * pI * J * tr**(J-1)
        if J not in (0,1):
            gtt += n * pI * J*(J-1) * tr**(J-2)
        if I >= 1 and J != 0:
            gpt += n * I * pr**(I-1) * J * tr**(J-1)
