class TestSnapshots:
    def test_basic_snapshot(self):
        doc = YDoc(700)
        doc.get_text('t').insert(0, 'hello')
        snap = doc.snapshot()
        doc.get_text('t').insert(5, ' world')
        assert str(doc.get_text('t')) == 'hello world'
        assert doc.text_at_snapshot('t', snap) == 'hello'

    def test_snapshot_with_deletes(self):
        doc = YDoc(700)
        doc.get_text('t').insert(0, 'hello world')
        snap1 = doc.snapshot()
        doc.get_text('t').delete(5, 6)
        snap2 = doc.snapshot()
        doc.get_text('t').insert(5, '!')
        assert str(doc.get_text('t')) == 'hello!'
        assert doc.text_at_snapshot('t', snap1) == 'hello world'
        assert doc.text_at_snapshot('t', snap2) == 'hello'

    def test_snapshot_after_remote_sync(self):
        doc1 = YDoc(701)
        doc1.get_text('t').insert(0, 'ab')

        doc2 = YDoc(702)
        doc2.apply_update_v1(doc1.encode_state_as_update_v1())
        doc2.get_text('t').insert(2, 'cd')

        snap = doc2.snapshot()
        doc2.get_text('t').insert(4, 'ef')

        assert str(doc2.get_text('t')) == 'abcdef'
        assert doc2.text_at_snapshot('t', snap) == 'abcd'
