def oracle_apply(text_name, *files):
    """Run the Yjs oracle to apply binary updates and return the text."""
    result = subprocess.run(
        ['node', '/app/yjs_oracle.js', 'apply', text_name] + list(files),
        capture_output=True, text=True, timeout=30
    )
    if result.returncode != 0:
        raise RuntimeError(f"Oracle failed: {result.stderr}")
    return json.loads(result.stdout)['text']


def write_tmp_bin(data):
    """Write binary data to a temp file, return its path."""
    fd, path = tempfile.mkstemp(suffix='.bin', dir='/tmp')
    os.write(fd, data)
    os.close(fd)
    return path


def load_manifest():
    with open('/app/fixtures/manifest.json') as f:
        return json.load(f)


