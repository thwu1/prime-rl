class TestCrossLanguageConvergence:
    def test_two_client_same_position(self):
        manifest = load_manifest()
        doc = YDoc(999)
        with open('/app/fixtures/client_a.bin', 'rb') as f:
            doc.apply_update_v1(f.read())
        with open('/app/fixtures/client_b.bin', 'rb') as f:
            doc.apply_update_v1(f.read())
        py_text = str(doc.get_text('t'))
        yjs_text = oracle_apply('t', '/app/fixtures/client_a.bin',
                                '/app/fixtures/client_b.bin')
        assert py_text == yjs_text
        assert py_text == manifest['concurrent_two']['expected_text']

    def test_three_client_same_position(self):
        manifest = load_manifest()
        doc = YDoc(999)
        for i in range(3):
            with open(f'/app/fixtures/three_{i}.bin', 'rb') as f:
                doc.apply_update_v1(f.read())
        py_text = str(doc.get_text('t'))
        yjs_text = oracle_apply('t', '/app/fixtures/three_0.bin',
                                '/app/fixtures/three_1.bin',
                                '/app/fixtures/three_2.bin')
        assert py_text == yjs_text
        assert py_text == manifest['concurrent_three']['expected_text']

    def test_commutativity_two_clients(self):
        """Applying updates in reverse order produces the same result."""
        doc1 = YDoc(999)
        with open('/app/fixtures/client_a.bin', 'rb') as f:
            data_a = f.read()
        with open('/app/fixtures/client_b.bin', 'rb') as f:
            data_b = f.read()

        doc1.apply_update_v1(data_a)
        doc1.apply_update_v1(data_b)

        doc2 = YDoc(998)
        doc2.apply_update_v1(data_b)
        doc2.apply_update_v1(data_a)

        assert str(doc1.get_text('t')) == str(doc2.get_text('t'))

    def test_five_client_convergence(self):
        manifest = load_manifest()
        doc = YDoc(999)
        with open('/app/fixtures/five_base.bin', 'rb') as f:
            doc.apply_update_v1(f.read())
        for i in range(5):
            with open(f'/app/fixtures/five_{i}.bin', 'rb') as f:
                doc.apply_update_v1(f.read())
        py_text = str(doc.get_text('t'))

        files = ['/app/fixtures/five_base.bin'] + \
                [f'/app/fixtures/five_{i}.bin' for i in range(5)]
        yjs_text = oracle_apply('t', *files)

        assert py_text == yjs_text
        assert py_text == manifest['five_concurrent']['expected_text']

    def test_concurrent_delete_and_insert(self):
        manifest = load_manifest()
        doc = YDoc(999)
        with open('/app/fixtures/del_ins_base.bin', 'rb') as f:
            doc.apply_update_v1(f.read())
        with open('/app/fixtures/del_ins_1.bin', 'rb') as f:
            doc.apply_update_v1(f.read())
        with open('/app/fixtures/del_ins_2.bin', 'rb') as f:
            doc.apply_update_v1(f.read())
        py_text = str(doc.get_text('t'))

        yjs_text = oracle_apply('t', '/app/fixtures/del_ins_base.bin',
                                '/app/fixtures/del_ins_1.bin',
                                '/app/fixtures/del_ins_2.bin')

        assert py_text == yjs_text
        assert py_text == manifest['concurrent_del_ins']['expected_text']


