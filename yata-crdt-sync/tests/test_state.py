# Diff-based sync across the language boundary
# ---------------------------------------------------------------------------

class TestDiffSync:
    def test_diff_sync_python_to_yjs(self):
        """Python creates a diff update, Yjs applies it correctly."""
        doc = YDoc(600)
        doc.get_text('t').insert(0, 'hello')
        base_sv = doc.get_state_vector()

        doc.get_text('t').insert(5, ' world')
        diff = doc.encode_state_as_update_v1(target_sv=base_sv)

        full = doc.encode_state_as_update_v1()
        tmp_full = write_tmp_bin(full)
        tmp_diff = write_tmp_bin(diff)
        try:
            yjs_full = oracle_apply('t', tmp_full)
            assert yjs_full == 'hello world'
        finally:
            os.unlink(tmp_full)
            os.unlink(tmp_diff)

    def test_bidirectional_divergent_sync(self):
        """Base + two divergent diffs converge."""
        manifest = load_manifest()
        doc = YDoc(999)
        with open('/app/fixtures/shared_base.bin', 'rb') as f:
            doc.apply_update_v1(f.read())
        with open('/app/fixtures/diverge_a.bin', 'rb') as f:
            doc.apply_update_v1(f.read())
        with open('/app/fixtures/diverge_b.bin', 'rb') as f:
            doc.apply_update_v1(f.read())
        py_text = str(doc.get_text('t'))

        yjs_text = oracle_apply('t', '/app/fixtures/shared_base.bin',
                                '/app/fixtures/diverge_a.bin',
                                '/app/fixtures/diverge_b.bin')

        assert py_text == yjs_text
        assert py_text == manifest['divergent_sync']['expected_text']


