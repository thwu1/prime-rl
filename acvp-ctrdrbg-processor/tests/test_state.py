class TestResponseSchema:
    @pytest.fixture(autouse=True)
    def load_response(self):
        with open(RESPONSE_PATH, "r") as f:
            self.response = json.load(f)

    def test_has_vsid(self):
        assert "vsId" in self.response, "Response missing 'vsId'"
        assert self.response["vsId"] == 42

    def test_has_algorithm(self):
        assert "algorithm" in self.response
        assert self.response["algorithm"] == "ctrDRBG"

    def test_has_test_groups(self):
        assert "testGroups" in self.response
        assert isinstance(self.response["testGroups"], list)
        assert len(self.response["testGroups"]) == 4

    def test_group_structure(self):
        for group in self.response["testGroups"]:
            assert "tgId" in group
            assert "tests" in group
            assert isinstance(group["tests"], list)
            for test in group["tests"]:
                assert "tcId" in test
                assert "returnedBits" in test

    def test_no_extra_properties_in_groups(self):
        for group in self.response["testGroups"]:
            allowed_keys = {"tgId", "tests"}
            extra = set(group.keys()) - allowed_keys
            assert not extra, f"tgId {group['tgId']}: unexpected keys {extra}"

    def test_no_extra_properties_in_tests(self):
        for group in self.response["testGroups"]:
            for test in group["tests"]:
                allowed_keys = {"tcId", "returnedBits"}
                extra = set(test.keys()) - allowed_keys
                assert not extra, (
                    f"tcId {test['tcId']}: unexpected keys {extra}"
                )


class TestReturnedBitsCorrectness:
    @pytest.fixture(autouse=True)
    def load_response(self):
        with open(RESPONSE_PATH, "r") as f:
            self.response = json.load(f)
        self.results = {}
        for group in self.response["testGroups"]:
            for test in group["tests"]:
                self.results[test["tcId"]] = test["returnedBits"]

    def _check_tc(self, tc_id):
        assert tc_id in self.results, f"Missing tcId {tc_id} in response"
        actual = self.results[tc_id].upper().replace(" ", "")
        expected = EXPECTED[tc_id].upper().replace(" ", "")
        assert actual == expected, (
            f"tcId {tc_id}: returnedBits mismatch.\n"
            f"  Expected first 64 chars: {expected[:64]}...\n"
            f"  Actual   first 64 chars: {actual[:64]}..."
        )

    def test_tc1_aes128_df_pr(self):
        """AES-128 with derivation function and prediction resistance, case 1"""
        self._check_tc(1)

    def test_tc2_aes128_df_pr(self):
        """AES-128 with derivation function and prediction resistance, case 2"""
        self._check_tc(2)

    def test_tc3_aes256_df_pr(self):
        """AES-256 with derivation function and prediction resistance, case 1"""
        self._check_tc(3)

    def test_tc4_aes256_df_pr(self):
        """AES-256 with derivation function and prediction resistance, case 2"""
        self._check_tc(4)

    def test_tc5_aes128_df_reseed(self):
        """AES-128 with derivation function, explicit reseed, case 1"""
        self._check_tc(5)

    def test_tc6_aes128_df_reseed(self):
        """AES-128 with derivation function, explicit reseed, case 2"""
        self._check_tc(6)

    def test_tc7_aes128_nodf_pr(self):
        """AES-128 without derivation function, prediction resistance, case 1"""
        self._check_tc(7)

    def test_tc8_aes128_nodf_pr(self):
        """AES-128 without derivation function, prediction resistance, case 2"""
        self._check_tc(8)


