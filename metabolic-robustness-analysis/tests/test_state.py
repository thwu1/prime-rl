# ---- Production envelope ----

def test_envelope_length(results):
    env = results["production_envelope"]
    assert len(env["growth_rates"]) == 11, (
        f"Expected 11 growth rates, got {len(env['growth_rates'])}"
    )
    assert len(env["max_ethanol"]) == 11, (
        f"Expected 11 max_ethanol, got {len(env['max_ethanol'])}"
    )


def test_envelope_growth_rates(results, ref):
    actual = results["production_envelope"]["growth_rates"]
    expected = ref["production_envelope"]["growth_rates"]
    for i in range(11):
        assert abs(actual[i] - expected[i]) < TOLERANCE, (
            f"Growth rate [{i}]: expected {expected[i]:.6f}, got {actual[i]}"
        )


def test_envelope_ethanol_values(results, ref):
    actual = results["production_envelope"]["max_ethanol"]
    expected = ref["production_envelope"]["max_ethanol"]
    for i in range(11):
        assert abs(actual[i] - expected[i]) < ENVELOPE_TOL, (
            f"Max ethanol [{i}]: expected {expected[i]:.4f}, got {actual[i]}"
        )


def test_envelope_zero_growth_positive_ethanol(results):
    env = results["production_envelope"]
    assert env["max_ethanol"][0] > 1.0, (
        f"At zero growth, ethanol should be positive, got {env['max_ethanol'][0]}"
    )


def test_envelope_growth_monotonic(results):
    gr = results["production_envelope"]["growth_rates"]
    for i in range(1, len(gr)):
        assert gr[i] >= gr[i - 1] - TOLERANCE, (
            f"Growth rates not monotonic at index {i}"
        )
