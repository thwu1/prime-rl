
"""
Verification tests for the VLIW SIMD kernel optimization task.
Tests correctness (bit-exact match with reference), performance (< 17000 cycles),
and profiling artifacts (profile report generated by vliw_profiler.py).
"""

import sys
import os
import json
import random
from copy import copy

sys.path.insert(0, "/app")

from problem import (
    Machine, Tree, Input, build_mem_image, reference_kernel2, N_CORES
)
from perf_takehome import KernelBuilder, BASELINE


def _run_kernel(forest_height, rounds, batch_size):
    """Run optimized kernel and return (correct, cycles)."""
    forest = Tree.generate(forest_height)
    inp = Input.generate(forest, batch_size, rounds)
    mem = build_mem_image(forest, inp)
    ref_mem = copy(mem)

    kb = KernelBuilder()
    kb.build_kernel(forest.height, len(forest.values), len(inp.indices), rounds)

    machine = Machine(mem, kb.instrs, kb.debug_info(), n_cores=N_CORES)
    machine.enable_pause = False
    machine.enable_debug = False
    machine.run()

    for rm in reference_kernel2(ref_mem):
        pass

    inp_values_p = ref_mem[6]
    inp_indices_p = ref_mem[5]
    n_vals = len(inp.values)
    n_idxs = len(inp.indices)

    values_correct = (
        machine.mem[inp_values_p: inp_values_p + n_vals]
        == ref_mem[inp_values_p: inp_values_p + n_vals]
    )
    indices_correct = (
        machine.mem[inp_indices_p: inp_indices_p + n_idxs]
        == ref_mem[inp_indices_p: inp_indices_p + n_idxs]
    )

    return values_correct and indices_correct, machine.cycle


