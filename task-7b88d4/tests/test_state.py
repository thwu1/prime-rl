class TestKernelPerformance:
    """Verify the optimized kernel meets the cycle count target."""

    def test_under_17000_cycles(self):
        random.seed(123)
        correct, cycles = _run_kernel(10, 16, 256)
        assert correct, "Output incorrect -- cannot evaluate performance"
        assert cycles < 17000, (
            f"Kernel took {cycles} cycles, target is < 17000. "
            f"Speedup: {BASELINE / cycles:.1f}x (need > {BASELINE / 17000:.1f}x)"
        )


class TestProfileReport:
    """Verify the profile report was generated using the vliw_profiler.py tool."""

    def test_report_exists(self):
        assert os.path.exists("/app/profile_report.json"), (
            "Profile report not found at /app/profile_report.json. "
            "Generate with: python3 /app/vliw_profiler.py report -o /app/profile_report.json"
        )

    def test_report_valid_json(self):
        with open("/app/profile_report.json") as f:
            report = json.load(f)
        assert isinstance(report, dict), "Report must be a JSON object"

    def test_report_structure(self):
        with open("/app/profile_report.json") as f:
            report = json.load(f)
        required_keys = [
            "profiler_version", "results", "slot_utilization",
            "configuration", "summary"
        ]
        for key in required_keys:
            assert key in report, f"Missing required key in report: {key}"
        assert "cycles" in report["results"], "Missing cycles in results"
        assert "correct" in report["results"], "Missing correct flag in results"
        assert "speedup" in report["results"], "Missing speedup in results"

    def test_report_shows_correct(self):
        with open("/app/profile_report.json") as f:
            report = json.load(f)
        assert report["results"]["correct"] is True, (
            "Profile report indicates kernel output is incorrect"
        )

    def test_report_cycles_consistent(self):
        """Verify the reported cycle count matches actual kernel execution."""
        with open("/app/profile_report.json") as f:
            report = json.load(f)
        reported_cycles = report["results"]["cycles"]

        # Run the kernel independently to cross-check the report
        seed = report["configuration"].get("seed", 123)
        random.seed(seed)
        correct, actual_cycles = _run_kernel(
            report["configuration"]["tree_height"],
            report["configuration"]["rounds"],
            report["configuration"]["batch_size"]
        )
        assert reported_cycles == actual_cycles, (
            f"Report claims {reported_cycles} cycles but kernel actually produces "
            f"{actual_cycles} cycles. Regenerate the report with: "
            "python3 /app/vliw_profiler.py report -o /app/profile_report.json"
        )

    def test_report_utilization_data(self):
        """Verify slot utilization data is present for all engines."""
        with open("/app/profile_report.json") as f:
            report = json.load(f)
        util = report["slot_utilization"]
        for engine in ["alu", "valu", "load", "store", "flow"]:
            assert engine in util, f"Missing utilization data for engine: {engine}"
            assert "slots_used" in util[engine], f"Missing slots_used for {engine}"
            assert "utilization_pct" in util[engine], (
                f"Missing utilization_pct for {engine}"
            )
            assert isinstance(util[engine]["slots_used"], int), (
                f"slots_used for {engine} must be an integer"
            )

    def test_report_performance_target(self):
        """Verify the profile report confirms the performance target is met."""
        with open("/app/profile_report.json") as f:
            report = json.load(f)
        cycles = report["results"]["cycles"]
        assert cycles < 17000, (
            f"Profile report shows {cycles} cycles, target is < 17000"
        )
