# Cross-validation: Python vs Octave reference
# ---------------------------------------------------------------------------

class TestCrossValidation:
    """Verify Python implementation matches Octave reference data."""

    def test_phi_matches_octave(self, reference_data):
        """Python phi values must match Octave reference within 1e-8."""
        from solver import phi

        assert "phi" in reference_data, "No Octave phi reference data"
        phi_data = reference_data["phi"]
        z_vals = phi_data[:, 0]
        max_err = 0.0

        for k in range(4):
            for i, z in enumerate(z_vals):
                py_val = float(np.real(phi(z, k)))
                oct_val = phi_data[i, k + 1]
                denom = max(abs(oct_val), 1e-15)
                err = abs(py_val - oct_val) / denom
                max_err = max(max_err, err)

        assert max_err < 1e-8, (
            f"Max phi relative error vs Octave: {max_err:.2e}"
        )

    def test_etd4rk_coefficients_match_octave(self, reference_data):
        """Python update coefficients must match Octave within 1e-8."""
        from solver import phi

        assert "coeffs" in reference_data, "No Octave coefficient data"
        coeff_data = reference_data["coeffs"]
        max_err = 0.0

        for i in range(coeff_data.shape[0]):
            hL = coeff_data[i, 0]
            p1 = float(np.real(phi(hL, 1)))
            p2 = float(np.real(phi(hL, 2)))
            p3 = float(np.real(phi(hL, 3)))

            py_a1 = p1 - 3 * p2 + 4 * p3
            py_a2 = 2 * (p2 - 2 * p3)
            py_a3 = -p2 + 4 * p3

            for py_val, col in [(py_a1, 1), (py_a2, 2), (py_a3, 3)]:
                oct_val = coeff_data[i, col]
                denom = max(abs(oct_val), 1e-15)
                err = abs(py_val - oct_val) / denom
                max_err = max(max_err, err)

        assert max_err < 1e-8, (
            f"Max coefficient relative error vs Octave: {max_err:.2e}"
        )

    def test_ks_solution_matches_octave(self, reference_data):
        """Python KS solution must match Octave reference within 0.01."""
        from solver import solve_ks

        assert "ks_ref" in reference_data, "No Octave KS reference data"
        ks_ref = reference_data["ks_ref"]

        u_python = solve_ks(L=32 * np.pi, N=64, T=1.0, dt=0.0625)
        max_err = np.max(np.abs(u_python - ks_ref))

        assert max_err < 0.01, (
            f"Max KS error vs Octave: {max_err:.2e} (threshold 0.01)"
        )


