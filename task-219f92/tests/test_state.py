# Convergence tests (pure Python)
# ---------------------------------------------------------------------------

class TestConvergence:
    """Test that the integrator achieves 4th-order convergence in time."""

    @classmethod
    def setup_class(cls):
        from scipy.integrate import solve_ivp
        sys.path.insert(0, "/app")
        from problem import setup, nonlinear

        params = setup(L=32 * np.pi, N=64)
        cls.k_wave = params["k"]
        cls.Lk = params["Lk"]
        cls.u0_hat = params["u0_hat"]
        cls.N_modes = 64

        def rhs(t, y):
            N = cls.N_modes
            u_hat = y[:N] + 1j * y[N:]
            dudt = cls.Lk * u_hat + nonlinear(u_hat, cls.k_wave)
            return np.concatenate([dudt.real, dudt.imag])

        y0 = np.concatenate([cls.u0_hat.real, cls.u0_hat.imag])
        sol = solve_ivp(
            rhs, [0, 1.0], y0, method="Radau",
            rtol=1e-12, atol=1e-14, max_step=0.01,
        )
        assert sol.success, f"Reference computation failed: {sol.message}"

        u_ref_hat = sol.y[:cls.N_modes, -1] + 1j * sol.y[cls.N_modes:, -1]
        cls.u_ref = np.fft.ifft(u_ref_hat).real

    def test_fourth_order_convergence(self):
        from solver import solve_ks

        dts = [0.25, 0.125, 0.0625]
        errors = []
        for dt in dts:
            u = solve_ks(L=32 * np.pi, N=64, T=1.0, dt=dt)
            assert u.shape == (64,), f"Expected shape (64,), got {u.shape}"
            err = np.max(np.abs(u - self.u_ref))
            errors.append(err)

        order1 = np.log2(errors[0] / errors[1])
        order2 = np.log2(errors[1] / errors[2])

        assert 3.0 < order1 < 5.5, (
            f"Expected order ~4, got {order1:.2f} "
            f"(errors: {errors[0]:.2e}, {errors[1]:.2e})"
        )
        assert 3.0 < order2 < 5.5, (
            f"Expected order ~4, got {order2:.2f} "
            f"(errors: {errors[1]:.2e}, {errors[2]:.2e})"
        )

    def test_accuracy_fine_dt(self):
        from solver import solve_ks
        u = solve_ks(L=32 * np.pi, N=64, T=1.0, dt=0.0625)
        max_err = np.max(np.abs(u - self.u_ref))
        assert max_err < 0.01, f"Max error {max_err:.2e} exceeds 0.01"


