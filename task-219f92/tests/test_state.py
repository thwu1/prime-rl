class TestPhiFunctions:
    """Test accuracy of Python phi-function implementation."""

    def test_phi0_scalar(self):
        from solver import phi
        for z in [-1.0, 0.0, 1.0, -10.0, 5.0]:
            result = phi(z, 0)
            expected = np.exp(z)
            assert abs(result - expected) < 1e-12, (
                f"phi_0({z})={result}, expected {expected}"
            )

    def test_phi1_moderate_z(self):
        from solver import phi
        for z in [-1.0, -5.0, -10.0, 1.0, 3.0]:
            result = phi(z, 1)
            expected = (np.exp(z) - 1) / z
            rel_err = abs(result - expected) / max(abs(expected), 1e-15)
            assert rel_err < 1e-8, (
                f"phi_1({z})={result}, expected {expected}, rel_err={rel_err}"
            )

    def test_phi2_moderate_z(self):
        from solver import phi
        for z in [-1.0, -5.0, 2.0, -20.0]:
            result = phi(z, 2)
            expected = (np.exp(z) - 1 - z) / z ** 2
            rel_err = abs(result - expected) / max(abs(expected), 1e-15)
            assert rel_err < 1e-8, (
                f"phi_2({z})={result}, expected {expected}, rel_err={rel_err}"
            )

    def test_phi3_moderate_z(self):
        from solver import phi
        for z in [-1.0, -5.0, 2.0, -20.0]:
            result = phi(z, 3)
            expected = (np.exp(z) - 1 - z - z ** 2 / 2) / z ** 3
            rel_err = abs(result - expected) / max(abs(expected), 1e-15)
            assert rel_err < 1e-8, (
                f"phi_3({z})={result}, expected {expected}, rel_err={rel_err}"
            )

    def test_phi1_near_zero(self):
        from solver import phi
        for z in [0.0, 1e-15, 1e-10, 1e-6, 1e-3]:
            result = phi(z, 1)
            expected = 1.0 + z / 2 + z ** 2 / 6 + z ** 3 / 24
            assert abs(result - expected) < 1e-6, (
                f"phi_1({z})={result}, expected ~{expected}"
            )

    def test_phi2_near_zero(self):
        from solver import phi
        for z in [0.0, 1e-15, 1e-10, 1e-6]:
            result = phi(z, 2)
            expected = 0.5 + z / 6 + z ** 2 / 24
            assert abs(result - expected) < 1e-6, (
                f"phi_2({z})={result}, expected ~{expected}"
            )

    def test_phi3_near_zero(self):
        from solver import phi
        for z in [0.0, 1e-15, 1e-10, 1e-6]:
            result = phi(z, 3)
            expected = 1.0 / 6 + z / 24 + z ** 2 / 120
            assert abs(result - expected) < 1e-6, (
                f"phi_3({z})={result}, expected ~{expected}"
            )

    def test_phi_complex_argument(self):
        from solver import phi
        z = 1.0 + 2.0j
        ez = np.exp(z)

        result1 = phi(z, 1)
        expected1 = (ez - 1) / z
        assert abs(result1 - expected1) < 1e-10

        result2 = phi(z, 2)
        expected2 = (ez - 1 - z) / z ** 2
        assert abs(result2 - expected2) < 1e-10

        result3 = phi(z, 3)
        expected3 = (ez - 1 - z - z ** 2 / 2) / z ** 3
        assert abs(result3 - expected3) < 1e-10

    def test_phi_array_input(self):
        from solver import phi
        z = np.array([-1.0, -5.0, -10.0, -0.1])
        for k in range(4):
            result = phi(z, k)
            assert hasattr(result, "__len__"), (
                f"phi({z}, {k}) should return array-like"
            )
            assert len(result) == len(z)

    def test_phi_mixed_magnitude_array(self):
        from solver import phi
        z = np.array([1e-12, -10.0, 0.0, -100.0])
        result = phi(z, 1)
        assert abs(result[0] - 1.0) < 1e-4
        expected_neg10 = (np.exp(-10.0) - 1) / (-10.0)
        assert abs(result[1] - expected_neg10) < 1e-8
        assert abs(result[2] - 1.0) < 1e-6
        expected_neg100 = (np.exp(-100.0) - 1) / (-100.0)
        assert abs(result[3] - expected_neg100) < 1e-8


