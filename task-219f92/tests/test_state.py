class TestKSProperties:
    """Test physical properties of the KS solution."""

    def test_solution_is_real(self):
        from solver import solve_ks
        u = solve_ks(L=32 * np.pi, N=64, T=1.0, dt=0.25)
        assert np.all(np.isfinite(u)), "Solution contains non-finite values"

    def test_mean_conservation(self):
        from solver import solve_ks
        from problem import setup

        params = setup(L=32 * np.pi, N=64)
        u0_mean = np.mean(np.fft.ifft(params["u0_hat"]).real)

        u = solve_ks(L=32 * np.pi, N=64, T=1.0, dt=0.25)
        final_mean = np.mean(u)

        assert abs(final_mean - u0_mean) < 1e-8, (
            f"Mean not conserved: initial={u0_mean:.2e}, final={final_mean:.2e}"
        )

    def test_correct_shape_and_type(self):
        from solver import solve_ks
        u = solve_ks(L=32 * np.pi, N=64, T=0.5, dt=0.25)
        assert isinstance(u, np.ndarray), "solve_ks must return numpy.ndarray"
        assert u.shape == (64,), f"Expected shape (64,), got {u.shape}"

    def test_different_parameters(self):
        from solver import solve_ks
        u = solve_ks(L=32 * np.pi, N=32, T=0.5, dt=0.25)
        assert u.shape == (32,), f"Expected shape (32,), got {u.shape}"
        assert np.all(np.isfinite(u)), "Solution contains non-finite values"
