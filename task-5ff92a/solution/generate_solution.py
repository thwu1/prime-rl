verify_prime_py = '''#!/usr/bin/env python3
"""
Extract the P-256 field prime from openssl ecparam output and verify
it matches the constant used in the library implementation.
"""
import subprocess
import re

# Known P-256 prime
p_256 = 2**256 - 2**224 + 2**192 + 2**96 - 1

# Extract curve parameters from openssl
try:
    output = subprocess.check_output(
        ["openssl", "ecparam", "-name", "prime256v1",
         "-param_enc", "explicit", "-text", "-noout"],
        stderr=subprocess.STDOUT
    ).decode()
except subprocess.CalledProcessError as e:
    print(f"openssl failed: {e}")
    with open("prime_verification.txt", "w") as f:
        f.write("MISMATCH\\n")
    exit(1)

# Parse the Prime field from the text output
# Format is colon-separated hex bytes on indented lines after "Prime:"
in_prime = False
hex_parts = []
for line in output.split("\\n"):
    stripped = line.strip()
    if stripped.startswith("Prime"):
        in_prime = True
        continue
    if in_prime:
        if line.startswith("    ") or line.startswith("\\t"):
            clean = stripped.replace(":", "").replace(" ", "")
            if clean and all(c in "0123456789abcdef" for c in clean):
                hex_parts.append(clean)
            else:
                if hex_parts:
                    break
        else:
            break

if not hex_parts:
    print("Failed to parse prime from openssl output")
    with open("prime_verification.txt", "w") as f:
        f.write("MISMATCH\\n")
    exit(1)

hex_str = "".join(hex_parts)
extracted_prime = int(hex_str, 16)

result = "MATCH" if extracted_prime == p_256 else "MISMATCH"
with open("prime_verification.txt", "w") as f:
    f.write(result + "\\n")

print(f"OpenSSL prime: {hex(extracted_prime)}")
print(f"Library prime: {hex(p_256)}")
print(f"Result: {result}")
'''

with open("/app/_verify_prime.py", "w") as f:
    f.write(verify_prime_py)
os.chmod("/app/_verify_prime.py", os.stat("/app/_verify_prime.py").st_mode | stat.S_IEXEC)

print("Generated /app/_verify_prime.py")
print("All solution files generated successfully.")
