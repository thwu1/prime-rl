class TestAllPass:
    def test_all_tests_pass(self, test_output):
        assert test_output["compiled"], "Compilation failed"
        output = test_output["output"]
        match = re.search(r'(\d+)/(\d+) tests passed', output)
        assert match, f"Could not find test summary in output:\n{output}"
        passed = int(match.group(1))
        total = int(match.group(2))
        assert passed == total, (
            f"Not all tests passed: {passed}/{total}\n{output}"
        )
