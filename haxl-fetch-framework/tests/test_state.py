
"""
Pytest verification for MicroHaxl concurrent data-fetching framework.
Checks compilation success and test results from the Haskell test driver.
"""

import subprocess
import os
import pytest
import re


def compile_and_run():
    """Compile and run the Haskell test driver, return (compile_ok, output)."""
    assert os.path.exists("/app/MicroHaxl.hs"), "MicroHaxl.hs not found"

    test_driver_path = "/app/TestDriver.hs"

    if not os.path.exists(test_driver_path):
        pytest.fail("TestDriver.hs not generated by test.sh")

    compile_result = subprocess.run(
        ["ghc", "-O0", "-o", "/app/test_runner",
         "/app/TestDriver.hs", "/app/MicroHaxl.hs",
         "-no-keep-hi-files", "-no-keep-o-files"],
        capture_output=True, text=True, timeout=120
    )

    if compile_result.returncode != 0:
        return False, compile_result.stderr

    run_result = subprocess.run(
        ["/app/test_runner"],
        capture_output=True, text=True, timeout=60
    )

    return True, run_result.stdout + run_result.stderr


@pytest.fixture(scope="session")
def test_output():
    """Run compilation and tests once, cache the result."""
    compiled, output = compile_and_run()
    return {"compiled": compiled, "output": output}


