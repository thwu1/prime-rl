G = 9.81


def run_pipeline(scenario_path):
    """Run the coastal pipeline CLI with a scenario file and return parsed JSON."""
    result = subprocess.run(
        ["python3", "/app/coastal_pipeline.py", scenario_path],
        capture_output=True, text=True, timeout=120
    )
    assert result.returncode == 0, (
        f"Pipeline returned exit code {result.returncode}.\n"
        f"stderr: {result.stderr}\nstdout: {result.stdout}"
    )
    try:
        return json.loads(result.stdout)
    except json.JSONDecodeError as e:
        pytest.fail(f"Invalid JSON output: {e}\nstdout: {result.stdout}")


def assert_close(actual, expected, rtol=0.05, atol=0.05, label=""):
    """Assert value within relative tolerance (for |expected|>0.1) or absolute."""
    prefix = f"[{label}] " if label else ""
    if abs(expected) > 0.1:
        rel_err = abs(actual - expected) / abs(expected)
        assert rel_err < rtol, (
            f"{prefix}Expected {expected:.6f}, got {actual:.6f} "
            f"(rel error {rel_err:.4f}, rtol={rtol})"
        )
    else:
        abs_err = abs(actual - expected)
        assert abs_err < atol, (
            f"{prefix}Expected {expected:.6f}, got {actual:.6f} "
            f"(abs error {abs_err:.4f}, atol={atol})"
        )


