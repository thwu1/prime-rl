# C LIBRARY — dispersion solver correctness via ctypes
# ===========================================================================
class TestCLibrary:
    @pytest.fixture(scope="class")
    def lib(self):
        lib_path = "/app/lib/libdispersion.so"
        assert os.path.isfile(lib_path), f"C library not found at {lib_path}"
        lib = ctypes.CDLL(lib_path)
        lib.solve_dispersion.argtypes = [
            ctypes.c_double, ctypes.c_double,
            ctypes.POINTER(ctypes.c_double)
        ]
        lib.solve_dispersion.restype = ctypes.c_int
        return lib

    def _call(self, lib, T, d):
        out = (ctypes.c_double * 5)()
        ret = lib.solve_dispersion(T, d, out)
        assert ret == 0, f"solve_dispersion returned {ret} for T={T}, d={d}"
        return {"L": out[0], "C": out[1], "Cg": out[2], "k": out[3], "n": out[4]}

    def test_deep_water_wavelength(self, lib):
        """At d=200m (deep water), L ~ Lo = g*T^2/(2*pi) ~ 156m."""
        r = self._call(lib, 10.0, 200.0)
        assert_close(r["L"], 156.13, rtol=0.03, label="C lib L at d=200")

    def test_deep_water_celerity(self, lib):
        r = self._call(lib, 10.0, 200.0)
        assert_close(r["C"], 15.61, rtol=0.03, label="C lib C at d=200")

    def test_deep_water_n(self, lib):
        """In deep water, n should be 0.5."""
        r = self._call(lib, 10.0, 200.0)
        assert_close(r["n"], 0.5, atol=0.01, label="C lib n deep water")

    def test_intermediate_wavelength(self, lib):
        """At d=3m, L ~ 53.3m per CEM Example II-1-1."""
        r = self._call(lib, 10.0, 3.0)
        assert_close(r["L"], 53.29, rtol=0.03, label="C lib L at d=3")

    def test_intermediate_celerity(self, lib):
        r = self._call(lib, 10.0, 3.0)
        assert_close(r["C"], 5.33, rtol=0.03, label="C lib C at d=3")

    def test_dispersion_relation_satisfied(self, lib):
        """Verify omega^2 = g*k*tanh(k*d) for computed results."""
        T = 10.0
        omega = 2.0 * math.pi / T
        omega_sq = omega ** 2
        for d in [200.0, 3.0, 0.5, 50.0]:
            r = self._call(lib, T, d)
            k = r["k"]
            rhs = G * k * math.tanh(k * d)
            rel = abs(omega_sq - rhs) / omega_sq
            assert rel < 1e-6, (
                f"Dispersion not satisfied at d={d}: "
                f"omega^2={omega_sq:.6f}, g*k*tanh(kd)={rhs:.6f}, rel={rel:.6e}"
            )

    def test_cg_equals_n_times_c(self, lib):
        """Verify Cg = n * C for all results."""
        r = self._call(lib, 10.0, 3.0)
        assert_close(r["Cg"], r["n"] * r["C"], rtol=0.001, label="Cg=n*C")

    def test_shallow_water_n(self, lib):
        """In very shallow water, n should approach 1.0."""
        r = self._call(lib, 10.0, 0.1)
        assert r["n"] > 0.9, f"n should approach 1.0 in shallow water, got {r['n']}"


