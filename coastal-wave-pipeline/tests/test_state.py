# SQLITE RESULTS — schema and data verification
# ===========================================================================
class TestSQLiteResults:
    def test_database_exists(self):
        assert os.path.isfile("/app/results.db"), "SQLite database not found at /app/results.db"

    def test_table_exists(self):
        conn = sqlite3.connect("/app/results.db")
        cursor = conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name='scenario_results'"
        )
        row = cursor.fetchone()
        conn.close()
        assert row is not None, "Table 'scenario_results' not found in database"

    def test_schema_columns(self):
        """Verify scenario_results table has required columns."""
        conn = sqlite3.connect("/app/results.db")
        cursor = conn.execute("PRAGMA table_info(scenario_results)")
        columns = {row[1] for row in cursor.fetchall()}
        conn.close()
        required = {"id", "scenario_name", "mode", "input_json", "output_json", "timestamp"}
        missing = required - columns
        assert not missing, f"Missing columns in scenario_results: {missing}"

    def test_results_present(self):
        """After make all, results should be in the database."""
        conn = sqlite3.connect("/app/results.db")
        cursor = conn.execute("SELECT COUNT(*) FROM scenario_results")
        count = cursor.fetchone()[0]
        conn.close()
        assert count > 0, "No results in database after pipeline run"

    def test_result_json_parseable(self):
        """Stored output_json must be valid JSON."""
        conn = sqlite3.connect("/app/results.db")
        cursor = conn.execute("SELECT output_json FROM scenario_results LIMIT 1")
        row = cursor.fetchone()
        conn.close()
        assert row is not None, "No results found"
        data = json.loads(row[0])
        assert isinstance(data, dict), "output_json should parse to a dict"

    def test_dispersion_in_db(self):
        """Run dispersion scenario and verify result is stored in DB."""
        run_pipeline("/app/scenarios/dispersion.json")
        conn = sqlite3.connect("/app/results.db")
        cursor = conn.execute(
            "SELECT output_json FROM scenario_results WHERE mode = 'dispersion'"
        )
        row = cursor.fetchone()
        conn.close()
        assert row is not None, "Dispersion result not found in database"
        data = json.loads(row[0])
        assert "results" in data

    def test_scenario_name_unique(self):
        """scenario_name should be UNIQUE — no duplicates."""
        conn = sqlite3.connect("/app/results.db")
        cursor = conn.execute(
            "SELECT scenario_name, COUNT(*) FROM scenario_results GROUP BY scenario_name HAVING COUNT(*) > 1"
        )
        duplicates = cursor.fetchall()
        conn.close()
        assert len(duplicates) == 0, f"Duplicate scenario names found: {duplicates}"

    def test_multiple_modes_in_db(self):
        """Database should contain results from multiple different modes."""
        conn = sqlite3.connect("/app/results.db")
        cursor = conn.execute("SELECT DISTINCT mode FROM scenario_results")
        modes = {row[0] for row in cursor.fetchall()}
        conn.close()
        assert len(modes) >= 3, f"Expected results from multiple modes, got: {modes}"
