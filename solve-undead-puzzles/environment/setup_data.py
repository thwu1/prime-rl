def main():
    os.makedirs('/app/src', exist_ok=True)
    os.makedirs('/app/solutions', exist_ok=True)
    with open('/app/puzzles.bin', 'wb') as f:
        f.write(base64.b64decode(BIN_B64))
    with open('/app/meta.db', 'wb') as f:
        f.write(base64.b64decode(DB_B64))
    with open('/app/puzzles.bin', 'rb') as f:
        magic = f.read(4)
        version, count = struct.unpack('<II', f.read(8))
    assert magic == b'UNDD', 'Bad magic'
    assert version == 2, 'Bad version: {}'.format(version)
    assert count == 7, 'Bad count: {}'.format(count)
    print('Verified: {} v{} {} puzzles'.format(magic, version, count))


if __name__ == '__main__':
    main()
