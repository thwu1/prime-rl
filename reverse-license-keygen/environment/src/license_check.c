static inline uint64_t ror64(uint64_t v, unsigned int n) {
    n &= 63;
    return (v >> n) | (v << (64 - n));
}

/* Stage 1: Character-by-character mixing hash */
static uint64_t hash_username(const char *user, size_t len) {
    uint64_t h = UINT64_C(0x243F6A8885A308D3);
    size_t i;
    for (i = 0; i < len; i++) {
        h ^= (uint64_t)(unsigned char)user[i];
        h *= UINT64_C(0x100000001B3);
        h = ror64(h, 17);
        h += UINT64_C(0x9E3779B97F4A7C15);
        h ^= h >> 31;
    }
    return h;
}

/* Stage 2: S-box substitution on each byte */
static uint64_t substitute(uint64_t h) {
    union { uint64_t u; uint8_t b[8]; } v;
    v.u = h;
    int i;
    for (i = 0; i < 8; i++) {
        v.b[i] = SBOX[v.b[i]];
    }
    return v.u;
}

/* Stage 3: 4-round Feistel network */
static uint64_t feistel(uint64_t h) {
    uint32_t L = (uint32_t)(h >> 32);
    uint32_t R = (uint32_t)(h & UINT32_C(0xFFFFFFFF));
    const uint32_t rk[4] = {
        UINT32_C(0xDEADBEEF), UINT32_C(0x0BADF00D),
        UINT32_C(0xFEEDFACE), UINT32_C(0x27182818)
    };
    const uint32_t rm[4] = {
        UINT32_C(0x1337CAFE), UINT32_C(0xCAFEBABE),
        UINT32_C(0xC0FFEE42), UINT32_C(0x31415927)
    };
    const unsigned int rs[4] = {7, 11, 5, 13};
    int i;
    for (i = 0; i < 4; i++) {
        uint32_t f = R * rm[i];
        f ^= R >> rs[i];
        f += rk[i];
        uint32_t tmp = L ^ f;
        L = R;
        R = tmp;
    }
    return ((uint64_t)L << 32) | (uint64_t)R;
}

/* Stage 4: Avalanche finalization (murmur3-like) */
static uint64_t finalize(uint64_t h) {
    h ^= h >> 33;
    h *= UINT64_C(0xFF51AFD7ED558CCD);
    h ^= h >> 33;
    h *= UINT64_C(0xC4CEB9FE1A85EC53);
    h ^= h >> 33;
    return h;
}

/* Derive license key from username */
static void derive_key(const char *username, char *out) {
    size_t len = strlen(username);
    uint64_t h = hash_username(username, len);
    h = substitute(h);
    h = feistel(h);
    h = finalize(h);
    snprintf(out, 20, "%04" PRIx64 "-%04" PRIx64 "-%04" PRIx64 "-%04" PRIx64,
             (h >> 48) & 0xFFFF, (h >> 32) & 0xFFFF,
             (h >> 16) & 0xFFFF, h & 0xFFFF);
}

int main(void) {
    char username[256], key[256];
    fprintf(stderr, "Username: ");
    if (!fgets(username, sizeof(username), stdin)) return 1;
    username[strcspn(username, "\n")] = 0;
    fprintf(stderr, "License Key: ");
    if (!fgets(key, sizeof(key), stdin)) return 1;
    key[strcspn(key, "\n")] = 0;
    if (!*username || !*key) { puts("INVALID"); return 1; }
    char expected[20];
    derive_key(username, expected);
    if (strcmp(key, expected) == 0) {
        puts("VALID");
        return 0;
    }
    puts("INVALID");
    return 1;
}
